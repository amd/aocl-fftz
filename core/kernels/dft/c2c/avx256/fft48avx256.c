static const ops_cycles_t ops_cnt[NUM_PRECISIONS] = {
                                                { 0, 184, 396, 1472, 108, 0 },
                                                { 0, 184, 396, 736, 108, 0 }};

ops_cycles_t get_ops_cnt_fft48avx256(FFTZ_UINT8 precision, FFTZ_UINT8 direction)
{
    if (precision == DT_FLOAT)
    {
        return ops_cnt[0];
    }
    else
    {
        return ops_cnt[1];
    }
}

